# print() boleh menerima teks, nombor, dan beberapa nilai sekali gus.
print("Hello, World!")
print(2026)
print(3.14)

# print() tanpa nilai menghasilkan satu baris kosong.
print()
print("Selepas baris kosong")

print("Python", "3.12", "Windows")

# sep menukar pemisah antara nilai. Lalai ialah satu ruang.
print("A", "B", "C", sep="-")

# end menukar aksara di hujung output. Lalai ialah newline.
print("Hello", end=" ")
print("World")
